package com.qingyu.app.data.repo

/**
 * 温度 → 发表情包的积极度喵。
 *
 * 用户明确要求：**聊天温度越高，它发表情包的频率就越高**，
 * 并且 **温度 0.6 基本意味着"只要表情包库里有符合情境的，他就会发"** 喵。
 *
 * 为什么要有这张表，而不是一句"适当发表情包"喵：
 * 模型对"适当""偶尔"这类副词没有稳定的标尺，同一个词在 0.3 和 1.5 的温度下
 * 会被它理解成差不多的频率。给出**具体档位 + 大致的间隔**，
 * 它才有一根可校准的锚，温度变化才真的体现为频率变化喵。
 *
 * 抽成纯函数是因为这是产品定的映射，得能被逐条钉住；
 * 而且"哪个温度落在哪一档"这种边界，在真机上要试好多次才能确认喵。
 */
object StickerEagerness {

    /**
     * 积极度档位喵。**顺序即频率递增**，比较大小用来判断谁更积极喵。
     */
    enum class Level {
        /** 几乎不用表情包喵。 */
        OFF,

        /** 很少用，只在特别贴切时喵。 */
        RARE,

        /** 偶尔用喵。 */
        OCCASIONAL,

        /** **只要库里有符合情境的就发出来**——用户点名的 0.6 落在这一档喵。 */
        EAGER,

        /** 发得勤，一有机会就配一个喵。 */
        FREQUENT,

        /** 非常频繁，经常整条回复就只有一个表情包喵。 */
        CONSTANT,
    }

    /**
     * 按温度取档位喵。
     *
     * 分界值是按用户那句话定的喵：0.6 必须落在 [Level.EAGER]，
     * 所以 EAGER 的下界取 0.55、上界到 0.8，让 0.6 和默认的 0.7 都在里面喵。
     * 再往上温度越高越积极，往下则递减到几乎不发喵。
     *
     * 温度区间是 0..2（设置页滑块），超出范围也按端点处理，
     * 免得出现"负温度没有任何档位"这种漏洞喵。
     */
    fun levelFor(temperature: Double): Level = when {
        temperature < 0.20 -> Level.OFF
        temperature < 0.40 -> Level.RARE
        temperature < 0.55 -> Level.OCCASIONAL
        temperature < 0.80 -> Level.EAGER
        temperature < 1.20 -> Level.FREQUENT
        else -> Level.CONSTANT
    }

    /**
     * 注入系统提示词的那段说明喵。
     *
     * 每档都带一个**大致间隔**：只给形容词模型会飘，给了"每几条里发一次"
     * 它才有东西可对齐喵。
     */
    fun instruction(level: Level): String = when (level) {
        Level.OFF ->
            "【发表情包的频率】\n这个角色现在几乎不用表情包，把话好好说完就行。"

        Level.RARE ->
            "【发表情包的频率】\n用得很省：大约每十来条回复里才发一次，而且只在特别贴切的时候。"

        Level.OCCASIONAL ->
            "【发表情包的频率】\n偶尔发一个：大约每 5～8 条回复里发一次。"

        Level.EAGER ->
            "【发表情包的频率】\n" +
                "**只要表情包库里有符合当前情境的，就发出来**——不要犹豫，也别觉得可有可无。" +
                "大约每 2～3 条回复里就该有一个表情包。"

        Level.FREQUENT ->
            "【发表情包的频率】\n" +
                "发得勤一些：一有机会就配个表情包，大约每 1～2 条回复里就发一次。"

        Level.CONSTANT ->
            "【发表情包的频率】\n" +
                "非常频繁地发表情包：经常整条回复就只有一个表情包、没有文字。" +
                "大约每 3 条回复里就有 2 条带表情包。"
    }
}
