package com.qingyu.app.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * **不跟随主题**的固定色喵。
 *
 * 为什么需要这一组，而不是把所有颜色都塞进 `Color.kt` 的语义槽喵：
 * 应用里有几个界面是**刻意固定外观**的，它们不该随浅色/暗色切换喵——
 *
 * - **语音通话页**：全屏沉浸，永远是深色。跟随主题的话，
 *   白天接通话会变成刺眼的白屏，而通话界面本来就该"沉下去"喵
 * - **头像裁剪页**：要压住照片本身的颜色，永远用深底 + 白色控件，
 *   否则浅色主题下裁剪框会被照片吃掉喵
 * - **图片查看器**：看图的背景必须是深色，否则照片的明暗会被背景干扰喵
 * - **红包**：品牌色是固定的红与金，跟着主题变就不像红包了喵
 *
 * 它们以前散落在各个文件里当 `private val` 或就地内联的 `Color(0x...)`喵。
 * 那种写法有两个问题喵：同一个"深底"在三个文件里各写一遍（改不齐就会
 * 出现三个略微不同的黑），以及**看不出这是刻意的**——
 * 后来的人会以为是漏改的硬编码，顺手换成主题色，于是设计就被改坏了喵。
 *
 * 收在这里之后，"固定色"成了一个**有名字、有理由、集中可查**的东西喵。
 */
object FixedColors {

    // ---------------------------------------------------------------- 沉浸式深色底

    /**
     * 通话页的背景喵。
     *
     * 带一点蓝调（不是纯黑）喵：纯黑在大屏上会显得"关机"，
     * 而这一版深蓝灰更有"夜色里通话"的质感，也让绿色的波形与按钮跳得出来喵。
     */
    val immersiveBackground = Color(0xFF14161C)

    /** 图片查看器与头像裁剪的底色：比通话页更接近纯黑，让照片成为唯一焦点喵。 */
    val photoBackdrop = Color(0xFF111111)

    /** 压在照片上的遮罩（60% 黑）喵。 */
    val photoScrim = Color(0x99000000)

    // ---------------------------------------------------------------- 沉浸式界面上的前景

    /**
     * 沉浸式界面上的主文字与图标喵。
     *
     * **不用 `Color.White`** 喵：纯白配深底在 OLED 上会有明显的边缘光晕，
     * 而略带灰的白（#F2F2F2）读起来更柔和、也更耐看喵。
     */
    val onImmersive = Color(0xFFF2F2F2)

    /** 裁剪框：接近纯白，因为它要精确地标示边界喵。 */
    val cropFrame = Color(0xF2FFFFFF)

    /** 三分构图网格线：淡到不抢镜，但看得见喵。 */
    val cropGrid = Color(0x4DFFFFFF)

    /** 沉浸式界面上的次级文字喵。 */
    val onImmersiveMuted = Color(0xB3FFFFFF)

    /** 沉浸式界面上的控件底色（8% 白）喵。 */
    val immersiveControl = Color(0x14FFFFFF)

    // ---------------------------------------------------------------- 通话页的强调色

    /** 说话时的声波与头像光环：比主题绿更亮，在深底上才跳得出来喵。 */
    val callAccent = Color(0xFF7ED9A0)

    /** 通话页渐变按钮的深端喵。 */
    val callAccentDeep = Color(0xFF4FB477)

    /** 通话页未激活按钮的渐变（深灰）喵。 */
    val callIdleStart = Color(0xFF3A3F4B)
    val callIdleEnd = Color(0xFF2A2E38)

    /** 深绿按钮上的图标色：用暗绿而不是白，避免"白圆里一个白图标"喵。 */
    val onCallAccent = Color(0xFF10331F)

    // ---------------------------------------------------------------- 红包

    /** 红包红喵。比错误红更暖一点，像纸质的红包喵。 */
    val packetRed = Color(0xFFE0574A)

    /** 红包的暗部（封口与阴影）喵。 */
    val packetRedDeep = Color(0xFFC0392B)

    /** 红包上的金色字喵。 */
    val packetGold = Color(0xFFF5C46B)

    // ---------------------------------------------------------------- 消息气泡

    /**
     * 浅色主题下自己气泡里的文字喵。
     *
     * 微信的浅绿气泡（#95EC69）上必须用深字才看得清，
     * 而主题的 `onSurface` 在暗色下是白的——所以这个值**不能**用语义槽喵。
     */
    val onUserBubbleLight = Color(0xFF111111)

    // ---------------------------------------------------------------- 未读徽标

    /**
     * 未读红点的底色喵。
     *
     * 与主题的 `error` 同色但不是同一个语义喵：这是"有新消息"的提示，
     * 不是错误。分开命名是为了以后想单独调整它时不必动错误色喵。
     */
    val unreadBadge = Color(0xFFFA5151)
}
